export function isBasicOrFormSlug(slug: string): boolean {
  const item = figmaSource.componentPages.find((p) => toSlug(p.name) === slug);
  return item?.category === "Basic" || item?.category === "Form";
}

export function listInteractiveBasicFormSlugs(): string[] {
  return Object.values({ ...basicFormDocs, button: buttonDoc, input: inputDoc, checkbox: checkboxDoc, link: linkDoc })
    .filter((d) => d.interactive)
    .map((d) => d.slug);
}
